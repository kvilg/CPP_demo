// Этот файл намеренно НЕ собирается до конца — и в этом весь смысл.
//
// Запустить:
//     cmake --build --preset debug --target Linked_double
//
// Увидишь ошибки линковки вида:
//     undefined reference to `List<double>::addLast(double const&)'
//     undefined reference to `List<double>::getValue(unsigned long long)'
//
// Обрати внимание: компиляция проходит. Падает ЛИНКОВКА. Компилятору
// хватило объявлений из List.h, чтобы выпустить вызовы, а тел он не
// нашёл — их никто не выпустил.
//
// Почему так. Тела методов List лежат в List.cpp, и подставить их
// компилятор может только там. В самом конце List.cpp стоит строка
//
//     template class List<int>;
//
// она и просит выпустить код всех методов для int. Для double такой
// строки нет, поэтому вызовы отсюда остаются висеть в воздухе.
//
// Починить можно двумя способами, и они взаимоисключающие:
//
//   1. Дописать в конец List.cpp ещё одну строку:
//          template class List<double>;
//      Минута работы, но каждый новый тип придётся добавлять руками,
//      и список никогда не станет по-настоящему шаблонным.
//
//   2. Перенести реализацию из List.cpp в List.h. Тогда список
//      заработает с любым типом сам, без всяких инстанцирований. Но
//      вместе с реализацией в заголовок придётся вернуть и определение
//      Node — то есть отказаться от того, что сейчас он спрятан.
//      Об этом же написано в разделе «Как устроено» в README.
//
// Второй способ — это и есть «переделать шаблон по-другому».
//
// И отдельно, уже после того как List<double> заработает: у него не
// будет operator<=> с категорией strong_ordering. Сравнение double
// даёт partial_ordering, потому что NaN не равен ничему, даже себе.
// Поэтому возвращаемый тип у нас выводится через
// std::compare_three_way_result_t<T>, а не прибит гвоздями.

#include <iostream>

#include "List.h"

int main() {
    List<double> list;
    list.addLast(1.5);
    list.addLast(2.5);
    list.addStart(0.5);

    std::cout << "размер: " << list.getSize() << '\n';
    for (std::size_t i = 0; i < list.getSize(); ++i) {
        std::cout << list.getValue(i) << ' ';
    }
    std::cout << '\n';

    return 0;
}
