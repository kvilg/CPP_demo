// --- чего здесь не хватает по заданию ---
//
// 1. СИГНАЛ. Требуется регулярный непрерывный сигнал, а шлётся
//    std::rand() % 50 — шум. Пока это не периодическая функция,
//    задавать нечего: у случайных чисел нет ни амплитуды, ни периода.
//    С этого и надо начинать, пункт 2 упирается сюда.
//
// 2. ИНТЕРФЕЙС. В задании сказано про «генерацию указанного сигнала» —
//    значит кто-то его указывает. Сейчас указывать негде: консольная
//    программа с захардкоженным поведением. Эмулятору нужен свой UI,
//    где задаются форма сигнала, амплитуда, период и частота отправки.
//
//    Требование задания «управление отдельно амплитудой и периодом»
//    относится именно сюда: это параметры генерации. Регистратор их не
//    трогает — он рисует то, что пришло, и даёт смотреть на это мышкой.
//
// 3. НЕСКОЛЬКО КЛИЕНТОВ. Это сверх задания, оно про такое молчит, но
//    эмулятор, которого хватает ровно на одного слушателя, выглядит
//    недоделанным. Сейчас nextPendingConnection() вызывается один раз
//    ДО цикла, поэтому сокет достаётся первому подключившемуся. Второй
//    клиент соединится на уровне TCP — слушающий сокет открыт, ядро
//    завершит рукопожатие — и будет молча ждать данных, которых не
//    будет никогда.
//
//    Делается вместе с переходом на цикл событий: app.exec(), сигнал
//    newConnection, список сокетов, рассылка в каждый. Тогда же само
//    собой решается и отслеживание отключений, которого тоже нет.
//
// Полная сверка с заданием — в qt/README.md.

int main(int argc, char* argv[]) {
    qtlog::install();

    QCoreApplication app(argc, argv);

    QTcpServer server;

    if (!server.listen(QHostAddress(QHostAddress::Any), 1234)) {
        qWarning("Не удалось занять порт 1234: %s", qPrintable(server.errorString()));
        return 1;
    }

    qInfo("Слушаю порт 1234. Подключись к 127.0.0.1:1234");

    if (!server.waitForNewConnection(30000)) {
        qInfo("Никто не подключился. Выход.");
        return 1;
    }

    QTcpSocket* client = server.nextPendingConnection();
    qInfo("Клиент подключился. Жду сообщения...");

    while (true) {

        const QByteArray out = QByteArray::number(std::rand() % 50) + "\n";
        if (client->state() == QAbstractSocket::ConnectedState) {
            client->write(out);
            client->waitForBytesWritten(100);
        }
        std::this_thread::sleep_for(std::chrono::seconds(1));
    }

    client->close();
    qInfo("Готово.");
    return 0;
}
